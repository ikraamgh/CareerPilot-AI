"use client";

import {
  FileText,
  BookOpen,
  Layers,
  CheckSquare,
  ChevronDown,
  ChevronUp,
} from "lucide-react";
import { useState } from "react";
import { mockImprovementPlan } from "@/lib/mock-data";
import { ImprovementItem } from "@/lib/types";
import { PageHeader } from "@/components/shared/PageHeader";
import { DemoBanner } from "@/components/shared/DemoBanner";
import { cn } from "@/lib/utils";

const iconMap: Record<string, React.ElementType> = {
  FileText,
  BookOpen,
  Layers,
  CheckSquare,
};

const priorityStyles: Record<string, string> = {
  high: "bg-red-50 border-red-200 text-red-700",
  medium: "bg-amber-50 border-amber-200 text-amber-700",
  low: "bg-slate-100 border-slate-200 text-slate-600",
};

const priorityLabels: Record<string, string> = {
  high: "High",
  medium: "Medium",
  low: "Low",
};

function ImprovementCard({ item }: { item: ImprovementItem }) {
  const [expanded, setExpanded] = useState(false);
  return (
    <div className="bg-white border border-slate-200 rounded-xl overflow-hidden hover:shadow-sm transition-shadow">
      <button
        onClick={() => setExpanded(!expanded)}
        className="w-full flex items-start gap-3 p-4 text-left"
      >
        <div className="flex-1 min-w-0">
          <div className="flex items-center gap-2 flex-wrap">
            <p className="text-sm font-semibold text-slate-800">{item.title}</p>
            <span
              className={cn(
                "text-[11px] font-medium px-2 py-0.5 rounded-full border",
                priorityStyles[item.priority]
              )}
            >
              {priorityLabels[item.priority]} priority
            </span>
          </div>
          <p className="text-xs text-slate-500 mt-1 line-clamp-2">{item.description}</p>
        </div>
        <div className="shrink-0 mt-0.5">
          {expanded ? (
            <ChevronUp className="w-4 h-4 text-slate-400" />
          ) : (
            <ChevronDown className="w-4 h-4 text-slate-400" />
          )}
        </div>
      </button>
      {expanded && (
        <div className="px-4 pb-4 border-t border-slate-100">
          <p className="text-sm text-slate-600 mt-3 leading-relaxed">{item.description}</p>
          {item.actionable && (
            <div className="mt-3 flex gap-2 p-3 bg-lime-50 border border-lime-200 rounded-lg">
              <span className="text-lime-600 shrink-0">→</span>
              <p className="text-xs font-medium text-lime-800">{item.actionable}</p>
            </div>
          )}
        </div>
      )}
    </div>
  );
}

export function ImprovementPage() {
  return (
    <div className="space-y-6">
      <PageHeader
        title="Improvement Plan"
        description="Personalized recommendations to strengthen your job search and career profile."
      />

      <DemoBanner
        type="info"
        message="ℹ️ The recommendations below are demo content based on common career advice patterns. In Phase 2, they will be generated by AI based on your actual resume and recent job analyses."
      />

      <div className="space-y-8">
        {mockImprovementPlan.map((category) => {
          const Icon = iconMap[category.icon] ?? FileText;
          return (
            <div key={category.id}>
              <div className="flex items-center gap-2 mb-4">
                <div className="w-8 h-8 bg-emerald-100 rounded-lg flex items-center justify-center">
                  <Icon className="w-4 h-4 text-emerald-600" />
                </div>
                <h2 className="text-base font-bold text-slate-900">{category.title}</h2>
                <span className="text-xs text-slate-400 bg-slate-100 px-2 py-0.5 rounded-full">
                  {category.items.length} items
                </span>
              </div>
              <div className="space-y-3">
                {category.items.map((item) => (
                  <ImprovementCard key={item.id} item={item} />
                ))}
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
}
